    val systemVariableNames: Set<String> = variables.keys.toSet()

    // -----------------------------------------------------------------------
    // 分类 API（A4，#11 P0-2）
    //
    // 原版把内建函数/方法统装在一张 `methodList` 里（FunctionMethodCreator.cs:9040-9316，
    // 恰好 271 条，与本文件的 [functions]/[methods] 逐字一致），并**双注册**：
    // - 语句位：`foreach (method in FunctionMethodCreator.GetMethodList()) if (!funcDic.ContainsKey(key))
    //   funcDic.Add(key, new FunctionIdentifier(key, method.Value, methodInstruction));`
    //   （FunctionIdentifier.cs:4140-4148）→ 行首出现这些名字即 METHOD 语句；
    // - 表达式位：`GetFunctionMethod(..., arguments != null)` 查 `methodDic` → `FunctionMethodTerm`
    //   （IdentifierDictionary.cs:566-586）。
    // 因此**不存在**「函数表 / 方法表」二分；拆表会同时破坏两侧，属回归（ADR-001 逐位契约）。
    // 真正需要区分的是**调用形态**：
    // - `NAME(...)`（有括号）→ methodDic 命中，合法；
    // - 裸 `NAME`（无括号）→ `GetFunctionMethod(arguments == null)` 只查 `refmethodDic`
    //   （用户 `@` 引用方法，IdentifierDictionary.cs:538-547），内建方法一律返回 null；
    //   随后 nameDic 判为 SystemMethod（:170）→ :607-612 抛
    //   「用变量的方式使用函数名"NAME"」。
    // [isBuiltinMethod] 即该判据（见 [IdentifierResolver.canBeReferencedBare] 的接线）。
    // -----------------------------------------------------------------------

    /** 是否原版 `methodList` 成员（= 表达式位可 `NAME(...)` 调用、语句位可作 METHOD）。 */
    fun isBuiltinMethod(name: String): Boolean = name.uppercase() in methods

    /** 内建函数/方法的静态返回类型；null = 不是 methodList 成员。 */
    fun isBuiltinFunction(name: String): Boolean = name.uppercase() in functions

    /**
     * 同时是**语句名**（[FunctionCode]）与内建方法名的 6 个名字：
     * `ENCODETOUNI` / `GETTIME` / `POWER` / `PRINTCPERLINE` / `SAVENOS` / `VARSIZE`。
     *
     * 原版 `if (!funcDic.ContainsKey(key))`（FunctionIdentifier.cs:4142）对它们**跳过** METHOD 注册，
     * 故语句位由自身 FunctionCode 胜出；我们的 [LineParser.parseCodeLine] 先查
     * `FunctionCode.BY_NAME` 再查 [methods]，顺序等价。
     */
    val statementShadowedMethods: Set<String> = methods.filter { name ->
        FunctionCode.BY_NAME.containsKey(name)
    }.toSet()
